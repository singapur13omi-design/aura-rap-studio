interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: typeof translations.sk;
}

const I18nContext = createContext<I18nContextType>({
  language: 'sk',
  setLanguage: () => {},
  t: translations.sk,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>('sk');

  useEffect(() => {
    const saved = localStorage.getItem('aura_rap_studio_lang') as Language;
    if (saved === 'sk' || saved === 'en') {
      setLanguageState(saved);
    }
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('aura_rap_studio_lang', lang);
  };

  const t = translations[language] || translations.sk;

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
